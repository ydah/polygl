import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const runtimeRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.resolve(
  runtimeRoot,
  "../crates/polygl-cli/assets/runtime.js",
);
const inputs = [
  "dist/generated/abi.js",
  "dist/generated/ops.js",
  "dist/errors.js",
  "dist/random.js",
  "dist/records.js",
  "dist/capabilities.js",
  "dist/validation.js",
  "dist/math3d.js",
  "dist/mesh.js",
  "dist/renderer.js",
  "dist/shader.js",
  "dist/scene.js",
  "dist/session.js",
  "dist/index.js",
];

const modules = await Promise.all(
  inputs.map(async (relativePath) => {
    const source = await readFile(path.join(runtimeRoot, relativePath), "utf8");
    return stripInternalImports(source).trim();
  }),
);
const bundle = [
  "// @generated by `pnpm --dir runtime build`; do not edit manually.",
  "",
  ...modules,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current;
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    throw new Error(`${outputPath} is missing; run pnpm --dir runtime build`);
  }
  if (current !== bundle) {
    throw new Error(`${outputPath} is stale; run pnpm --dir runtime build`);
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, bundle);
}

function stripInternalImports(source) {
  return source
    .split("\n")
    .filter(
      (line) =>
        !line.startsWith("import ") &&
        !(line.startsWith("export {") && line.includes(' from "./')),
    )
    .join("\n");
}
